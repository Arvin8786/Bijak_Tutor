export function arithmeticChallenge(index,level=1,kind='add'){
 const n=Math.max(0,Math.floor(Number(index)||0)),l=Math.min(3,Math.max(1,Number(level)||1));
 const cap=[0,9,20,100][l]; const a=1+((n*7+3)%(cap-1));
 const b=1+((n*11+5)%(cap-1));const first=kind==='subtract'?Math.max(a,b):a,second=kind==='subtract'?Math.min(a,b):b;
 const answer=kind==='subtract'?first-second:first+second;
 const opts=[answer,answer+1,answer+2,Math.max(0,answer-1)].filter((x,i,s)=>s.indexOf(x)===i).slice(0,3);
 return {first,second,answer,options:opts.sort((x,y)=>((x*7+n)%19)-((y*7+n)%19))};
}
export function getPattern(index){const entry=SEQUENCE_PATTERNS[index%SEQUENCE_PATTERNS.length];const shown=entry.tiles.length===2?[...entry.tiles,...entry.tiles]:[...entry.tiles];return {...entry,shown}}
export function buildWordSearch(index,size=9){
 const terms=WORDSEARCH_WORDS[index%WORDSEARCH_WORDS.length];
 // Deterministic horizontal placement, one word per row; no fake hidden words.
 const grid=Array.from({length:size},(_,r)=>Array.from({length:size},(_,c)=>'ABCDEFGHIJKLMNOPQRSTUVWXYZ'[(r*17+c*11+index*13)%26]));
 terms.forEach((word,r)=>{const offset=(index+r*2)%(size-word.length+1);[...word].forEach((ch,i)=>grid[r][i+offset]=ch)});
 return {terms,grid};
}
